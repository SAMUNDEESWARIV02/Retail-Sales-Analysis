SELECT
    o.order_id,
    o.order_date,
    oi.product_id,
    p.product_name,
    oi.quantity,
    p.list_price,
    oi.discount
FROM orders o
INNER JOIN order_items oi
    ON o.order_id = oi.order_id
INNER JOIN products p
    ON oi.product_id = p.product_id;
    
    
