## TASK 4 Write a query to group sales (total_price) by each store_id.
SELECT s.store_id,s.store_name, SUM(oi.quantity*oi.list_price) As Total_price
FROM stores As s
INNER JOIN orders o ON s.store_id = o.store_id
INNER JOIN order_items oi on o.order_id = oi.order_id
GROUP BY s.store_id;

## TASK 5 Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.
SELECT oi.product_id,p.product_name,SUM(quantity) As Total_quantity
FROM order_items As oi
INNER JOIN products As p ON oi.product_id = p.product_id
GROUP BY oi.product_id
ORDER BY (Total_quantity) DESC
LIMIT 5;

## TASK 6 For each customer, return total orders placed, total items purchased, and total revenue
SELECT c.customer_id,COUNT(o.order_id) As Total_orders,
SUM(oi.quantity)As Total_items,
SUM(oi.quantity*oi.list_price)As Total_revenue FROM customers As c
INNER JOIN orders o ON c.customer_id = o.customer_id
INNER JOIN order_items oi ON o.order_id = oi.order_id
GROUP BY c.customer_id;

## TASK 7 Write a query to classify customers into spending brackets (e.g., low,medium, high).
SELECT c.customer_id,SUM(oi.quantity*oi.list_price)  As Total_spending,
CASE 
WHEN Total_spending > 5000 then "HIGH"
WHEN Total_spending >= 2000 and Total_spending < 5000 then "MEDIUM"
WHEN Total_spending < 2000 then "LOW"
