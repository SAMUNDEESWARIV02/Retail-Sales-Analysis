## TASK 8 Analyze total revenue generated by each staff member based on their handled orders.
SELECT s.staff_id,s.first_name,s.last_name, SUM(oi.quantity*oi.list_price) As Total_revenue
FROM staffs As s
INNER JOIN orders As o ON s.staff_id = o.staff_id
INNER JOIN order_items As oi ON o.order_id = oi.order_id
GROUP BY  s.staff_id;

## TASK 9 Write a query to list products where stock quantity < 10 in any store.
SELECT p.product_id,p.product_name,s.store_id,s.quantity,st.store_name
FROM products As p
INNER JOIN stocks As s ON p.product_id = s.product_id
INNER JOIN stores As st ON s.store_id = st.store_id
WHERE s.quantity < 10;
